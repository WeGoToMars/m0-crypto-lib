#!/usr/bin/env python3
"""Case table of a comparison board image (bench/board/build_compare.sh).

    python3 -I bench/board/gen_compare.py PRIMITIVE OUT.h

The workloads are those of bench/count.py (default lengths, aligned buffers; for X25519
the RFC 7748 section 6.1 keys plus two seeded pseudo-random inputs, as with
`count.py x25519 --random 2`) and the expected results come from bench/reference.py,
which is checked against the RFC test vectors first. Each case names one
run_IMPL_OP wrapper of bench/harness/, the wrapper the emulator counts.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import reference as r  # noqa: E402

LENGTHS = [0, 64, 256, 1024, 4096]
RANDOM_X25519 = 2


def arr(b: bytes) -> str:
    return "{" + ",\n    ".join(",".join(f"0x{x:02x}" for x in b[i:i + 32])
                               for i in range(0, max(len(b), 1), 32)) + "}" if b else "{0}"


class Table:
    def __init__(self, primitive):
        self.primitive = primitive
        self.arrays, self.cases, self.wrappers = [], [], set()

    def array(self, name, data: bytes) -> str:
        self.arrays.append(f"static const uint8_t {name}[{max(len(data), 1)}] = {arr(data)};")
        return name

    def case(self, impl, op, label, wrapper, length, key, nonce, aad, src, tag_in, out,
             tag_out, reject=False, keep=False):
        self.wrappers.add(wrapper)
        ref = lambda x: x if x else "0"
        self.cases.append(
            f'    {{"{impl}", "{op}", "{label}", {wrapper}, {length}, {aad[1]}, {int(reject)}, '
            f'{int(keep)}, {ref(key)}, {ref(nonce)}, {ref(aad[0])}, {ref(src[0])}, {src[1]}, '
            f'{ref(tag_in)}, {ref(out[0])}, {out[1]}, {ref(tag_out)}}},')

    def header(self) -> str:
        lines = [
            f"/* Generated by bench/board/gen_compare.py {self.primitive}; do not edit. */",
            f'#define CMP_PRIMITIVE "{self.primitive}"',
        ]
        lines += [f"void {w}(Job *);" for w in sorted(self.wrappers)]
        lines += self.arrays
        lines += [f"#define CMP_NCASES {len(self.cases)}",
                  "static const struct cmp_case cmp_cases[CMP_NCASES] = {"]
        lines += self.cases + ["};"]
        return "\n".join(lines) + "\n"


def chacha20poly1305(t: Table) -> None:
    r.check_rfc_vector()
    key, nonce, aad = bytes(range(32)), bytes(range(12)), bytes(range(16))
    pt = bytes(i % 251 for i in range(max(LENGTHS)))
    ct = r.chacha(key, nonce, pt)
    k, n, a = t.array("k", key), t.array("nonce", nonce), t.array("aad", aad)
    p, c = t.array("pt", pt), t.array("ct", ct)
    for length in LENGTHS:
        tag = r.tag_for(key, nonce, aad, ct[:length])
        good = t.array(f"tag{length}", tag)
        bad = t.array(f"badtag{length}", bytes([tag[0] ^ 1]) + tag[1:])
        for impl in ("m0c", "wolf", "mono", "ossl"):
            w = lambda op: f"run_{impl}_{op}"
            t.case(impl, "chacha", "", w("chacha"), length, k, n, (a, 16), (p, length), 0,
                   (c, length), 0)
            t.case(impl, "encrypt", "", w("encrypt"), length, k, n, (a, 16), (p, length), 0,
                   (c, length), good)
            t.case(impl, "decrypt", "", w("decrypt"), length, k, n, (a, 16), (c, length), good,
                   (p, length), 0)
            # wolfSSL has a different rejected-decrypt output convention (as in count.py).
            t.case(impl, "reject", "", w("decrypt"), length, k, n, (a, 16), (c, length), bad,
                   (0, length if impl != "wolf" else 0), 0, reject=True, keep=impl != "wolf")


def blake2s(t: Table) -> None:
    r.check_blake2s_vector()
    msg = bytes(i % 251 for i in range(max(LENGTHS)))
    m = t.array("msg", msg)
    for length in LENGTHS:
        d = t.array(f"digest{length}", r.blake2s(msg[:length]))
        for impl in ("m0c", "wolf", "ref", "ossl"):
            for op in ("hash", "stream"):
                t.case(impl, op, "", f"run_{impl}_{op}", length, 0, 0, (0, 0), (m, length), 0,
                       (d, 32), 0)


def x25519(t: Table) -> None:
    r.check_x25519_vectors()
    base = bytes([9]) + bytes(31)
    # bench/count.py x25519_inputs()
    inputs = [("rfc7748-6.1", "shared", r.clamp_scalar(r.ALICE_PRIVATE), r.BOB_PUBLIC),
              ("rfc7748-6.1", "public", r.clamp_scalar(r.ALICE_PRIVATE), base)]
    for index in range(RANDOM_X25519):
        seed = hashlib.sha256(f"m0c-bench-x25519-{index}".encode()).digest()
        inputs.append((f"random-{index}", "shared", r.clamp_scalar(seed),
                       r.x25519(hashlib.sha256(seed).digest(), base)))
    for i, (label, op, scalar, point) in enumerate(inputs):
        s, u = t.array(f"scalar{i}", scalar), t.array(f"point{i}", point)
        o = t.array(f"result{i}", r.x25519(scalar, point))
        for impl in ("m0c", "wolf", "pornin", "mono", "ossl"):
            t.case(impl, op, label, f"run_{impl}_{op}", 32, s, 0, (0, 0), (u, 32), 0, (o, 32), 0)


if __name__ == "__main__":
    primitive, path = sys.argv[1:]
    table = Table(primitive)
    {"chacha20poly1305": chacha20poly1305, "blake2s": blake2s, "x25519": x25519}[primitive](table)
    with open(path, "w") as f:
        f.write(table.header())
