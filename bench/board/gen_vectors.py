#!/usr/bin/env python3
"""Generate the expected-output tables for the board images.

    python3 -I bench/board/gen_vectors.py          # writes the two headers next to this file

Nothing here is a build dependency of the library. The tables are the *independent*
side of the on-board correctness gate:

* BLAKE2s digests come from Python's hashlib.blake2s over messages that the firmware
  regenerates with the same generator (fill() below mirrors fill_message() in
  common.c byte for byte).
* X25519 results come from a pure-Python RFC 7748 ladder that is itself checked here
  against the RFC 7748 test vectors and, where defined, against the `cryptography`
  package (OpenSSL) for random pairs.
"""
import hashlib
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# ---------------------------------------------------------------- BLAKE2s ----
LENS = [0, 1, 2, 3, 4, 5, 15, 16, 17, 31, 32, 33, 55, 56, 57, 63, 64, 65,
        127, 128, 129, 191, 192, 193, 255, 256, 257, 512, 1024, 2048, 4096]
FAMILIES = 5   # 0 zeros, 1 0xff, 2 xorshift A, 3 xorshift B, 4 counting pattern mod 251
MAX_LEN = 4096


def fill(family: int, n: int) -> bytes:
    if family == 0:
        return bytes(n)
    if family == 1:
        return b"\xff" * n
    if family == 4:
        return bytes(i % 251 for i in range(n))
    x = 0x2545F491 if family == 2 else 0x9E3779B9
    out = bytearray()
    for _ in range(n):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out.append((x >> 7) & 0xFF)
    return bytes(out)


def blake2s_header() -> str:
    lines = [
        "/* Generated by bench/board/gen_vectors.py; do not edit. Expected BLAKE2s-256 digests",
        " * (Python hashlib) of fill_message(family, len) for each length x family. */",
        f"#define B2_NLENS {len(LENS)}",
        f"#define B2_NFAMILIES {FAMILIES}",
        f"#define B2_MAX_LEN {MAX_LEN}",
        "static const unsigned b2_lens[B2_NLENS] = {" + ", ".join(map(str, LENS)) + "};",
        "static const uint8_t b2_expect[B2_NLENS][B2_NFAMILIES][32] = {",
    ]
    for n in LENS:
        row = []
        for f in range(FAMILIES):
            d = hashlib.blake2s(fill(f, n), digest_size=32).digest()
            row.append("{" + ",".join(f"0x{b:02x}" for b in d) + "}")
        lines.append("    {" + ",\n     ".join(row) + "},")
    lines.append("};")
    # RFC 7693 appendix E: BLAKE2s-256("abc").
    abc = hashlib.blake2s(b"abc", digest_size=32).digest()
    assert abc.hex() == "508c5e8c327c14e2e1a72ba34eeb452f37458b209ed63a294d999b4c86675982"
    lines.append("static const uint8_t b2_abc[32] = {" + ",".join(f"0x{b:02x}" for b in abc) + "};")
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------- X25519 ----
P = 2**255 - 19
A24 = 121665


def x25519(k: bytes, u: bytes) -> bytes:
    """RFC 7748 section 5 (Montgomery ladder, Python integers)."""
    kk = bytearray(k)
    kk[0] &= 248
    kk[31] &= 127
    kk[31] |= 64
    scalar = int.from_bytes(kk, "little")
    x1 = (int.from_bytes(u, "little") & ((1 << 255) - 1)) % P
    x2, z2, x3, z3, swap = 1, 0, x1, 1, 0
    for t in range(254, -1, -1):
        bit = (scalar >> t) & 1
        swap ^= bit
        if swap:
            x2, x3, z2, z3 = x3, x2, z3, z2
        swap = bit
        a = (x2 + z2) % P
        aa = a * a % P
        b = (x2 - z2) % P
        bb = b * b % P
        e = (aa - bb) % P
        c = (x3 + z3) % P
        d = (x3 - z3) % P
        da = d * a % P
        cb = c * b % P
        x3 = (da + cb) ** 2 % P
        z3 = x1 * (da - cb) ** 2 % P
        x2 = aa * bb % P
        z2 = e * (aa + A24 * e) % P
    if swap:
        x2, x3, z2, z3 = x3, x2, z3, z2
    return (x2 * pow(z2, P - 2, P) % P).to_bytes(32, "little")


def h(s: str) -> bytes:
    return bytes.fromhex(s)


def le(n: int) -> bytes:
    return n.to_bytes(32, "little")


BASE = le(9)
# RFC 7748 section 5.2 and 6.1 (strings typed from the RFC; asserted below).
R1K = h("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
R1U = h("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
R1O = h("c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552")
R2K = h("4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d")
R2U = h("e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493")
R2O = h("95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957")
IT1 = h("422c8e7a6227d7bca1350b3e2bb7279f7897b87bb6854b783c60e80311ae3079")
IT1000 = h("684cf59ba83309552800ef566f2f4d3c1c3887c49360e3875f2eb94d99532c51")
AK = h("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
AP = h("8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a")
BK = h("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
BP = h("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f")
SH = h("4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742")


def self_check() -> None:
    assert x25519(R1K, R1U) == R1O
    assert x25519(R2K, R2U) == R2O
    assert x25519(BASE, BASE) == IT1
    k = u = BASE
    for _ in range(1000):
        k, u = x25519(k, u), k
    assert k == IT1000, "RFC 7748 1000-iteration vector"
    assert x25519(AK, BASE) == AP and x25519(BK, BASE) == BP
    assert x25519(AK, BP) == SH and x25519(BK, AP) == SH


def vectors():
    """(label, scalar, point). Labels are short identifiers used in the log."""
    v = [
        ("rfc5.2-1", R1K, R1U),
        ("rfc5.2-2", R2K, R2U),
        ("rfc5.2-iter1", BASE, BASE),
        ("rfc6.1-a*B", AK, BP),
        ("rfc6.1-b*A", BK, AP),
        ("rfc6.1-a*9", AK, BASE),
        ("rfc6.1-b*9", BK, BASE),
    ]
    # Degenerate scalars with an ordinary point (clamping fixes bits 0-2, 254, 255).
    v += [
        ("k=0,rfc-u", bytes(32), R1U),
        ("k=ff..ff,rfc-u", b"\xff" * 32, R1U),
        ("k=0,u=9", bytes(32), BASE),
        ("k=ff..ff,u=9", b"\xff" * 32, BASE),
        ("k=1,u=9", le(1), BASE),
        ("k=2^254-8..,u=9", le(2**254 - 8), BASE),
        ("k=single-bit-7", le(1 << 7), R1U),
    ]
    # Low-order, zero and non-canonical points (all outputs are checked, not assumed).
    order8a = 325606250916557431795983626356110631294008115727848805560023387167927233504
    order8b = 39382357235489614581723060781553021112529911719440698176882885853963445705823
    pts = [
        ("u=0", 0), ("u=1", 1), ("u=order8a", order8a), ("u=order8b", order8b),
        ("u=p-1", P - 1), ("u=p", P), ("u=p+1", P + 1), ("u=p+18=2^255-1", 2**255 - 1),
        ("u=2^255(bit255)", 2**255), ("u=2^255+9", 2**255 + 9), ("u=2^256-1", 2**256 - 1),
        ("u=2", 2),
    ]
    for name, u in pts:
        v.append((f"R1K,{name}", R1K, le(u)))
    v.append(("k=ff..ff,u=0", b"\xff" * 32, le(0)))
    v.append(("k=0,u=order8a", bytes(32), le(order8a)))
    # Random pairs from a fixed seed (full 256-bit scalars and points, top bits included).
    rng = random.Random(0x4D30C)
    for i in range(16):
        v.append((f"random{i:02d}", rng.randbytes(32), rng.randbytes(32)))
    return v


def x25519_header() -> str:
    self_check()
    vs = vectors()
    try:
        from cryptography.hazmat.primitives.asymmetric import x25519 as cx
        checked = 0
        for label, k, u in vs:
            want = x25519(k, u)
            try:
                pub = cx.X25519PublicKey.from_public_bytes(u)
                got = cx.X25519PrivateKey.from_private_bytes(k).exchange(pub)
            except ValueError:
                continue  # OpenSSL refuses all-zero shared secrets
            assert got == want, f"cryptography disagrees on {label}"
            checked += 1
        print(f"cross-checked {checked}/{len(vs)} vectors against `cryptography`", file=sys.stderr)
    except ImportError:
        print("cryptography not installed: only the RFC vectors cross-check the ladder", file=sys.stderr)

    def arr(b: bytes) -> str:
        return "{" + ",".join(f"0x{x:02x}" for x in b) + "}"

    lines = [
        "/* Generated by bench/board/gen_vectors.py; do not edit. X25519 test pairs with results",
        " * from a pure-Python RFC 7748 ladder (self-checked against the RFC vectors). */",
        f"#define X_NVEC {len(vs)}",
        "struct x_vec { const char *label; uint8_t k[32], u[32], out[32]; };",
        "static const struct x_vec x_vecs[X_NVEC] = {",
    ]
    for label, k, u in vs:
        label = label.replace(",", ";")  # the log is comma-separated
        lines.append(f'    {{"{label}", {arr(k)},\n     {arr(u)},\n     {arr(x25519(k, u))}}},')
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(os.path.join(HERE, "blake2s_vectors.h"), "w") as f:
        f.write(blake2s_header())
    with open(os.path.join(HERE, "x25519_vectors.h"), "w") as f:
        f.write(x25519_header())
