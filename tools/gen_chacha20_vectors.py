#!/usr/bin/env python3
"""Generate tests/chacha20_vectors.h with pyca/cryptography (an independent implementation):

- ChaCha20 at chosen starting block counters, including calls that end exactly at counter
  0xffffffff (accepted) and calls one block past it (rejected with M0C_ERR_COUNTER, as
  include/m0crypto/chacha20.h states). Accepted calls up to 256 bytes carry their output.
- ChaCha20-Poly1305 with AAD and messages longer than 65,535 bytes. Only the tag is stored:
  it authenticates the whole ciphertext and both lengths. These run on the specification
  (proofs/tools/spec_vectors.py), not on QEMU.

Message and AAD bytes are CV_PATTERN(0, i) and CV_PATTERN(1, i).
Usage: tools/gen_chacha20_vectors.py > tests/chacha20_vectors.h"""
import hashlib

import cryptography
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

KEY = hashlib.sha256(b"m0-crypto chacha20 vectors: key").digest()
NONCE = hashlib.sha256(b"m0-crypto chacha20 vectors: nonce").digest()[:12]
# (counter, len): around 2^31 and the 2^32 boundary, and lengths too large for any buffer.
CHACHA = [(2, 130), (0x7fffffff, 129), (0xfffffffd, 191), (0xfffffffd, 193),
          (0xfffffffe, 128), (0xfffffffe, 129), (0xffffffff, 0), (0xffffffff, 1),
          (0xffffffff, 64), (0xffffffff, 65), (0xfc000000, 0xffffffff),
          (0xfc000001, 0xffffffff), (0xffffffff, 0xffffffff)]
MAXOUT = 256
# (AAD length, message length): byte 2 of each length field is non-zero.
AEAD_LONG = [(70000, 17), (15, 70001), (0x20003, 0x10005)]


def pattern(s, n):
    return bytes((i * 251 + (i >> 8) * 7 + s * 101) & 0xFF for i in range(n))


def accepted(counter, n):
    """include/m0crypto/chacha20.h: no block counter past 0xffffffff."""
    return counter + (n + 63) // 64 <= 2**32


def chacha20(counter, msg):
    nonce = counter.to_bytes(4, "little") + NONCE
    return Cipher(algorithms.ChaCha20(KEY, nonce), mode=None).encryptor().update(msg)


def cbytes(b, indent="    "):
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return (",\n" + indent).join(rows)


out, rows = b"", []
for counter, n in CHACHA:
    ok = accepted(counter, n)
    off = len(out)
    if ok and n <= MAXOUT:
        out += chacha20(counter, pattern(0, n))
    rows.append(f"    {{0x{counter:08x}u, {n}u, {0 if ok else -1}, {off}u}},")

print(f"""/* Generated by tools/gen_chacha20_vectors.py (pyca/cryptography {cryptography.__version__}). Do not edit.
 * Test image and proofs/tools/spec_vectors.py only. */
#include <stdint.h>
#define CV_PATTERN(s, i) ((uint8_t)((i) * 251u + ((i) >> 8) * 7u + (s) * 101u))
#define CV_MAXOUT {MAXOUT}
static const uint8_t cv_key[32] = {{
    {cbytes(KEY)}}};
static const uint8_t cv_nonce[12] = {{{cbytes(NONCE)}}};

/* ChaCha20 of CV_PATTERN(0, i) from block `counter`. result: 0 (M0C_OK) or -1
 * (M0C_ERR_COUNTER). An accepted call of at most CV_MAXOUT bytes has its output at
 * cv_out[out]. */
struct chacha_vec {{ uint32_t counter, len; int8_t result; uint16_t out; }};
static const struct chacha_vec chacha_vecs[] = {{""")
print("\n".join(rows))
print(f"""}};
static const uint8_t cv_out[] = {{
    {cbytes(out)}}};

/* ChaCha20-Poly1305 tag of message CV_PATTERN(0, i) and AAD CV_PATTERN(1, i). */
struct aead_long_vec {{ uint32_t aad_len, len; uint8_t tag[16]; }};
static const struct aead_long_vec aead_long_vecs[] = {{""")
for alen, n in AEAD_LONG:
    tag = ChaCha20Poly1305(KEY).encrypt(NONCE, pattern(0, n), pattern(1, alen))[-16:]
    print(f"    {{{alen}u, {n}u, {{{cbytes(tag)}}}}},")
print("};")
