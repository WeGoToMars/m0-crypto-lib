#!/usr/bin/env python3
"""Generate tests/blake2s_vectors.h: BLAKE2s-256 digests (Python hashlib, an independent
implementation) of the first n bytes of the pattern P[i] = (i*251 + 13) mod 256, for the
lengths the on-target test uses. Usage: tools/gen_blake2s_vectors.py > tests/blake2s_vectors.h"""
import hashlib

LENS = list(range(0, 201)) + [1024, 1025, 4096]
P = bytes((i * 251 + 13) & 0xFF for i in range(4096))
print("/* Generated by tools/gen_blake2s_vectors.py (hashlib.blake2s). Do not edit. */")
print("#include <stdint.h>")
print("#define B2V_PATTERN(i) ((uint8_t)((i) * 251u + 13u))")
print(f"#define B2V_COUNT {len(LENS)}")
print("static const uint16_t b2v_len[B2V_COUNT] = {" + ", ".join(map(str, LENS)) + "};")
print("static const uint8_t b2v_digest[B2V_COUNT][32] = {")
for n in LENS:
    d = hashlib.blake2s(P[:n]).digest()
    print("    {" + ", ".join(f"0x{b:02x}" for b in d) + "},")
print("};")
